package com.morak.dev;

/**
 * DEV-4가 이름으로 찾아 실행할 수 있는 배치. 구현은 각 도메인에 둔다(B1→session,
 * B2→match, B4→member).
 *
 * <p>구현이 하나뿐인 인터페이스는 만들지 않는 것이 이 프로젝트의 규칙이지만(CLAUDE.md §4-1),
 * 이것은 서비스의 추상화가 아니라 등록 지점이다. 배치는 셋이고 각각 다른 도메인에 있는데,
 * 개발용 컨트롤러가 그 셋을 직접 알면 dev 패키지가 모든 도메인을 향해 의존하게 된다.
 * 새 배치는 이 인터페이스만 구현하면 트리거에 자동으로 등록된다.
 */
public interface DevBatch {

    /** 명세의 배치 ID. {@code B1} | {@code B2} | {@code B4}. */
    String name();

    /** 처리한 건수를 돌려준다. 게이트에서 "정말 뭔가 바뀌었는지"를 확인하는 값이다. */
    int run();
}
